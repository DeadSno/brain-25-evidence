"""Заполняет поле `forms` для ТОП-20 самых популярных добавок (DATA-P2-11).

Берёт список widely-known добавок (см. пример в задаче) и, там где
`forms` равен null / пустому массиву, проставляет общеизвестные формы
выпуска. Не придумывает несуществующих форм, не меняет структуру JSON,
для остальных (~110) добавок оставляет `null` (честно, не выдумываем).

Формат поля — строка (как у уже заполненных записей, напр. Магний,
Омега-3, Витамин D).
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "docs" / "data.json"

# ТОП-20 самых популярных добавок (по общему признанию, см. задачу DATA-P2-11).
TOP20 = [
    "Креатин",
    "Омега-3",
    "Витамин D",
    "Магний",
    "Цинк",
    "Кальций",
    "Железо",
    "Витамин C",
    "Мелатонин",
    "Куркумин",
    "Кофеин",
    "B12",
    "CoQ10",
    "Витамин E",
    "Пробиотики",
    "Коллаген",
    "Ашваганда",
    "Гинкго",
    "BCAA",
    "Сывороточный протеин",
]

# Общеизвестные формы выпуска (только реально существующие).
FORMS = {
    "Креатин": "моногидрат (самый изученный, знак Creapure), микронизированный моногидрат, гидрохлорид (HCl)",
    "Цинк": "пиколинат, глицинат, цитрат, сульфат, оксид",
    "Кальций": "карбонат, цитрат, лактат, глюконат, хлорид",
    "Витамин C": "аскорбиновая кислота, натрия аскорбат, кальция аскорбат, липосомальный, эстер-С",
    "Куркумин": "экстракт куркумы (стандартизирован по куркумину), фитосомный/мицеллярный, с пиперином",
    "Кофеин": "безводный кофеин, кофеин цитрат, натуральный (кофе, чай, гуарана)",
    "B12": "цианокобаламин, метилкобаламин, аденозилкобаламин, гидроксокобаламин",
    "CoQ10": "убикинон, убихинол, микропизированный, липосомальный",
    "Витамин E": "д-альфа-токоферол, смесь токоферолов, токотриенолы",
    "Ашваганда": "экстракт корня (стандартизирован, напр. KSM-66 / Sensoril), порошок корня",
    "Гинкго": "экстракт листьев гинкго билоба (стандартизирован, напр. EGb 761)",
    "BCAA": "лейцин, изолейцин, валин (свободные аминокислоты; соотношения 2:1:1, 4:1:1, 8:1:1)",
    "Сывороточный протеин": "концентрат (WPC), изолят (WPI), гидролизат (WPH)",
}


def main() -> int:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    by_id = {rec["id"]: rec for rec in data}

    missing_top20 = [tid for tid in TOP20 if tid not in by_id]
    if missing_top20:
        print("[!] Не найдены в data.json:", missing_top20)
        return 1

    filled = 0
    already = 0
    for tid in TOP20:
        rec = by_id[tid]
        forms = rec.get("forms")
        if forms is None or forms == []:
            rec["forms"] = FORMS[tid]
            filled += 1
            print(f"[+] {tid}: forms заполнен")
        else:
            already += 1
            print(f"[-] {tid}: уже заполнено — {forms!r}, не трогаем")

    text = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    DATA.write_text(text, encoding="utf-8")

    print(f"\nИТОГ: {filled} добавок получили forms, {already} уже имели, "
          f"всего в ТОП-20: {len(TOP20)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
