def main():
    data = json.loads(DATA_PATH.read_text(encoding="utf-8"))
    filled = 0
    skipped = []
    for rec in data:
        if rec.get("forms") not in (None, ""):
            continue
        rid = rec.get("id")
        if rid in FORM_MAP:
            rec["forms"] = FORM_MAP[rid]
            filled += 1
        else:
            skipped.append(rid)
    DATA_PATH.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"filled forms: {filled}")
    print(f"still null (unknown form): {len(skipped)}")
    for rid in skipped:
        print("  ", rid)


if __name__ == "__main__":
    main()
