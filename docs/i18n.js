function t(key, params) {
  const dict = I18N[LOCALE] || I18N.ru;
  let s = dict[key] != null ? dict[key] : (I18N.ru[key] != null ? I18N.ru[key] : key);
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m));
  return s;
}

// 13A3 (I18N-P2-02): применение перевода к data-i18n-* атрибутам (title, aria-label,
// placeholder) после разбора DOM. root по умолчанию document; window.applyI18n
// оставлен для динамически вставляемой разметки.
function applyI18n(root) {
  root = root || document;
  root.querySelectorAll('[data-i18n-title]').forEach(el =>
    el.title = t(el.dataset.i18nTitle));
  root.querySelectorAll('[data-i18n-aria-label]').forEach(el =>
    el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel)));
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el =>
    el.placeholder = t(el.dataset.i18nPlaceholder));
  root.querySelectorAll('[data-i18n-text]').forEach(el =>
    el.textContent = t(el.dataset.i18nText));
}
// I2-01 (FIX-52): переключатель языка. Сама разметка <select id="langSelect">
// стоит в навбаре каждой страницы рядом с кнопкой темы, а вся логика —
// здесь, чтобы не дублировать её по 141 странице.
//
// Почему смена языка перезагружает страницу, а не перерисовывает текст:
// динамический контент (карточки, графики, таблицы, инспектор) рендерится
// один раз при инициализации и берёт строки через t() в момент отрисовки.
// Без перезагрузки уже нарисованное осталось бы на прежнем языке, то есть
// страница стала бы наполовину английской. Перезагрузка дешевле и честнее.
function setLocale(lang) {
  if (I18N_LANGS.indexOf(lang) === -1 || lang === LOCALE) return;
  try {
    localStorage.setItem(I18N_LANG_KEY, lang);
  } catch (e) { /* приватный режим: выбор не сохранится, но применится */ }
  location.reload();
}

function initLangSwitcher() {
  const sel = document.getElementById('langSelect');
  if (sel) {
    sel.value = LOCALE;
    sel.addEventListener('change', function () {
      setLocale(sel.value);
    });
  }
}

document.addEventListener('DOMContentLoaded', function () {
  applyI18n();
  initLangSwitcher();
});
window.applyI18n = applyI18n; // для динамики
window.setLocale = setLocale;
