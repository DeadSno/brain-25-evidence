// 13A2a (I18N-P2-01): единый глобальный i18n-модуль проекта.
// Classic-script (не module, без IIFE): I18N / t / LOCALE — глобальные,
// их используют docs/script.js, inline-скрипты тем в docs/*.html и
// templates/sup*.j2. Словарь перенесён сюда из script.js дословно
// (13A1 -> 13A2a): двух верхнеуровневых const I18N быть не может —
// classic-скрипты делят одну глобальную лексическую среду, дубль
// даёт SyntaxError и роняет второй скрипт целиком.
// v5.6.3 (I18N-P2-04): локаль берётся из <html lang>, а не вписывается в
// код. Раньше строки вроде toLocaleString('ru-RU') жили в разметке и в
// скриптах, и перевод страницы требовал правки каждого вызова по
// отдельности — при этом замена lang="en" в <html> давала бы английский
// текст вокруг и русские числа внутри. ru-RU и ru для Intl совпадают,
// поведение при ru не меняется.
let LOCALE = document.documentElement.lang || 'ru';
// I2-01 (FIX-52): приоритет у явного выбора пользователя — он лежит в
// localStorage('lang') и переживает перезагрузку. <html lang> остаётся
// значением по умолчанию, 'ru' — последним фолбэком.
// LOCALE объявлена через let, а не const: ниже она переопределяется.
// Валидация обязательна — в localStorage может лежать что угодно, а
// незнакомый код сделал бы I18N[LOCALE] === undefined и превратил бы
// каждую строку в её ключ.
const I18N_LANG_KEY = 'lang';
const I18N_LANGS = ['ru', 'en'];
try {
  const savedLang = localStorage.getItem(I18N_LANG_KEY);
  if (I18N_LANGS.indexOf(savedLang) !== -1) LOCALE = savedLang;
} catch (e) { /* приватный режим: localStorage может быть недоступен */ }
if (I18N_LANGS.indexOf(LOCALE) === -1) LOCALE = 'ru';
document.documentElement.lang = LOCALE;
// CWV-01 (BATCH-3): в EN страница сначала рисуется по-русски, а через
// 100–160 мс приходит перевод (applyI18n + data_en.json) и текст меняется —
// это давало CLS до 0,247 при пороге «poor» 0,1. Класс ставится здесь, до
// первой отрисовки: i18n.js подключён в <head> без defer, поэтому успевает
// раньше, чем браузер покажет main. Правило в style.css:
// html.i18n-pending main { visibility: hidden } — место под контент
// сохраняется, но пользователь не видит русский текст, который вот-вот
// сменится (иначе виден именно скачок).
if (LOCALE === 'en') document.documentElement.classList.add('i18n-pending');
var _i18nPendingTimer = null;
function releaseI18nPending() {
  if (!document.documentElement.classList.contains('i18n-pending')) return;
  document.documentElement.classList.remove('i18n-pending');
  if (_i18nPendingTimer !== null) {
    clearTimeout(_i18nPendingTimer);
    _i18nPendingTimer = null;
  }
}
// Эти страницы подменяют контент уже после DOMContentLoaded: карточка sup/*,
// каталог sup/index.html и Hactar ждут data_en.json. Для них завесу снимает
// сам loadEnCards (см. ниже), а таймаут — только страховка от вечной пустоты
// при офлайне или 404.
function needsEnData() {
  var body = document.body;
  if (!body) return false;
  return body.hasAttribute('data-sup-id') ||
    !!document.querySelector('a[data-sup-id]') ||
    body.classList.contains('hactar-page');
}
if (LOCALE === 'en') {
  _i18nPendingTimer = setTimeout(releaseI18nPending, 1500);
}
