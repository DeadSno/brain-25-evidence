def grade_of(g, volume):
    """Грейд доказательности из силы эффекта (Hedges' g) и объёма науки.
    volume — scienceIndex карточки (объём строчек/цитат, не мета-объём).
    """
    if g is None:
        return None
    if volume < 50:
        return "D"
    if g >= 0.4 and volume >= 100:
        return "A"
    if g >= 0.2:
        return "B"
    return "C"


