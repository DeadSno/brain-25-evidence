"""Каждая страница с содержанием о БАДах несёт дисклеймер.

Зачем этот тест
---------------
LEGAL-P2-01 требовал дисклеймер на двух файлах: docs/offline.html и
docs/google4a9d23e35c6c3e23.html. Проверка показала, что это ложное
срабатывание аудита, и вот почему.

`docs/google4a9d23e35c6c3e23.html` — **не страница**. Это файл
верификации Google Search Console, содержимое которого обязано
дословно совпадать с выданным токеном:

    google-site-verification: <token>

Добавление любого текста, включая дисклеймер, делает токен
недействительным — Google перестаёт проходить проверку. В файле нет
тега <html>, он никогда не рендерится как документ и не содержит ни
одного утверждения о здоровье.

`docs/offline.html` — страница ошибки «нет соединения». Она
показывает заголовок, кнопку «Обновить» и ссылку «На главную». Утверждений
о БАДах на ней нет, предъявлять к ней требование о дисклеймере — значит
втыкать юридический текст в экран, где пользователь ищет кнопку
обновления. Футер у неё отсутствует намеренно (см. комментарий в её
шапке: страница полностью автономна, стили инлайновые, чтобы работать
офлайн).

Закрытие долга — не «дописать текст», а **зафиксировать правило и
исключения в гейте**, чтобы дефект не вернулся на других 144
страницах и чтобы следующий аудит не поднял тот же ложный флаг.

Что тест проверяет
------------------
1. Каждый HTML-документ в docs/ и docs/sup/ содержит блок class="disc"
   (источники данных) и блок class="legal-disclaimer" с правовой
   формулировкой «БАД не является лекарственным» — кроме двух
   перечисленных исключений, каждое с записанной причиной.

   FIX-38 (FOOTER-01): до этого гейт требовал фразу «Не медицинская
   рекомендация» из блока .disc. Блок .disc сокращён до перечня
   источников — предупреждений о вреде самолечения в футере было два
   (пересказ + правовая формулировка), и владелец видел один и тот же
   смысл трижды. Правовая формулировка осталась в .legal-disclaimer,
   поэтому гейт теперь проверяет именно её: смысл требования не
   ослаб, он привязан к точному тексту, а не к пересказу.
2. Список исключений не растёт молча: каждый элемент всё ещё
   существует, всё ещё не содержит дисклеймера и всё ещё относится к
   своему типу (токен верификации / страница ошибки). Если файл
   перестанет соответствовать причине — тест падает и заставляет
   перечитать решение, а не молча оставить его в списке.
3. Покрытие не схлопнулось в ноль: страниц должно быть не меньше
   100 (замер 2026-10-12: 144).
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"

DISC_CLASS = 'class="disc"'
LEGAL_CLASS = 'class="legal-disclaimer"'
DISC_TEXT = "БАД не является лекарственным"
#: Текст, который Google Search Console требует дословно. Если он есть в
#: файле, файл - токен верификации, а не страница.
GOOGLE_TOKEN = "google-site-verification:"

#: Единственные файлы без дисклеймера, с причиной на каждое.
EXEMPT: dict[str, str] = {
    "offline.html":
        "страница ошибки «нет соединения»: ни одного утверждения "
        "о БАДах, футера нет намеренно (автономная страница, "
        "стили инлайновые)",
    "google4a9d23e35c6c3e23.html":
        "токен верификации Google Search Console: любое "
        "добавление текста обесценивает проверку домена",
}


def _pages() -> list[Path]:
    return sorted(list(DOCS.glob("*.html")) + list(DOCS.glob("sup/*.html")))


def _is_page(path: Path) -> bool:
    """Отсеивает токены верификации: у них нет тега <html>."""
    return "<html" in path.read_text(encoding="utf-8").lower()


def test_every_claiming_page_carries_the_disclaimer():
    missing = []
    for p in _pages():
        text = p.read_text(encoding="utf-8")
        if not _is_page(p):
            continue                      # токен верификации, не документ
        if p.name in EXEMPT:
            continue                      # исключение с записанной причиной
        if DISC_CLASS not in text or LEGAL_CLASS not in text or DISC_TEXT not in text:
            missing.append(p.relative_to(DOCS.parent).as_posix())
    assert not missing, (
        f"Страница без дисклеймера ({len(missing)}):\n"
        + "\n".join(f"  {f}" for f in missing)
        + "\nДисклеймер — это <p class=\"legal-disclaimer\"> в футере страницы. "
          "Если страница сознательно без него, добавь её в EXEMPT "
          "в этом файле вместе с причиной."
    )


def test_non_page_files_are_google_tokens():
    """Файл без <html> обязан быть токеном верификации, а не мусором."""
    for p in _pages():
        if _is_page(p):
            continue
        text = p.read_text(encoding="utf-8")
        rel = p.relative_to(DOCS.parent).as_posix()
        assert GOOGLE_TOKEN in text, (
            f"{rel} не содержит тега <html и не является токеном "
            f"верификации. Подтверди, что это мусор, и удали файл."
        )


def test_exemption_list_still_matches_reality():
    """Исключения не должны устареть молча.

    Проверяем все три условия, на которых основано исключение: файл
    существует, дисклеймера в нём по-прежнему нет, и он по-прежнему
    относится к заявленному типу. Если страница обзаведётся дисклеймером
    или перестанет быть страницей ошибки — исключение надо пересмотреть
    вручную, а не оставить висеть.
    """
    for name, reason in EXEMPT.items():
        matches = list(DOCS.rglob(name))
        assert matches, (
            f"EXEMPT содержит {name}, которого больше нет в docs/. "
            f"Причина в записи была: {reason}"
        )
        for path in matches:
            rel = path.relative_to(DOCS.parent).as_posix()
            text = path.read_text(encoding="utf-8")
            assert DISC_TEXT not in text, (
                f"{rel} в списке EXEMPT, но дисклеймер в нём появился. "
                "Значит исключение больше не нужно — убери его, иначе "
                "тест перестанет проверять эту страницу."
            )
            if reason.startswith("токен верификации"):
                assert GOOGLE_TOKEN in text, (
                    f"{rel} числится токеном верификации, но в нём нет "
                    f"токена {GOOGLE_TOKEN!r}. Пересмотри исключение."
                )
            else:
                assert _is_page(path), (
                    f"{rel} числится страницей ошибки, но тега <html "
                    "в нём нет — значит это не та страница. "
                    "Пересмотри исключение."
                )


def test_disclaimer_gate_covers_the_whole_site():
    """Страховка от молчаливого схлопывания охвата в ноль."""
    n = sum(1 for p in _pages() if _is_page(p))
    assert n >= 100, (
        f"Гейт дисклеймера проверил {n} страниц, ожидалось не меньше "
        f"100 (замер 2026-10-12: 144). Похоже, разбор в <html> сломан."
    )


def test_no_orphan_exemptions():
    """В EXEMPT не должно быть файлов, которых нет на диске."""
    listed = set(EXEMPT)
    actual = {
        p.name
        for p in DOCS.rglob("*.html")
        if not _is_page(p) or (
            LEGAL_CLASS not in p.read_text(encoding="utf-8")
        )
    }
    stale = sorted(listed - actual)
    assert not stale, (
        f"EXEMPT перечисляет {', '.join(stale)}, но на диске такой файл "
        f"уже содержит дисклеймер либо не существует. Убери запись."
    )